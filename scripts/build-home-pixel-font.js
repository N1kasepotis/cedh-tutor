const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const sourcePath = path.join(
  root,
  'tools',
  'fonts',
  'fusion-pixel-10px-monospaced-zh_hans-home-subset.ttf',
);
const outputPath = path.join(root, 'miniprogram', 'assets', 'home-pixel-font.js');

const base64 = fs.readFileSync(sourcePath).toString('base64');
const output = `/*
 * Fusion Pixel Font 10px Monospaced zh_hans - homepage subset
 * Upstream: https://github.com/TakWolf/fusion-pixel-font - release 2026.07.01
 * Font license: SIL Open Font License 1.1
 * Full licenses: tools/fonts/FUSION_PIXEL_OFL.txt and miniprogram/assets/FUSION_PIXEL_OFL.txt
 * Generated by scripts/build-home-pixel-font.js - do not edit the base64 by hand.
 */
const homePixelFontBase64 = '${base64}';

module.exports = { homePixelFontBase64 };
`;

fs.writeFileSync(outputPath, output, 'utf8');
console.log(`Generated ${path.relative(root, outputPath)} (${base64.length} base64 chars)`);
