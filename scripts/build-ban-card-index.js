'use strict';
// Rebuild with official Scryfall print IDs so the list never needs 43 metadata requests.
const fs = require('fs');
const path = require('path');
const { banlist } = require('../miniprogram/community/shared/catalog');
const { card } = require('../miniprogram/community/shared/contracts');
async function main() {
  const response = await fetch('https://api.scryfall.com/cards/collection', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Accept: 'application/json',
      'User-Agent': 'cEDH-Tutor/1.0',
    },
    body: JSON.stringify({ identifiers: banlist.cards.map(({ name }) => ({ name })) }),
    signal: AbortSignal.timeout(30000),
  });
  if (!response.ok) throw new Error(`Scryfall HTTP ${response.status}`);
  const result = await response.json();
  if (!Array.isArray(result.data) || result.not_found?.length)
    throw new Error('Incomplete ban card response');
  const index = {};
  for (const entry of banlist.cards) {
    const raw = result.data.find(
      (value) =>
        value.name === entry.name ||
        value.card_faces?.some((face) => face.name === entry.name),
    );
    if (!raw) throw new Error(`Missing exact card: ${entry.name}`);
    const normalized = card(raw);
    if (!normalized.image || !normalized.art)
      throw new Error(`Missing card image: ${entry.name}`);
    index[entry.id] = {
      printId: normalized.printId,
      name: normalized.name,
      image: normalized.image,
      art: normalized.art,
      artist: normalized.artist,
    };
  }
  fs.writeFileSync(
    path.join(__dirname, '../miniprogram/community/shared/ban-cards.js'),
    '// Generated by scripts/build-ban-card-index.js\nmodule.exports = ' +
      JSON.stringify(index, null, 2) +
      ';\n',
  );
  console.log(`Indexed ${Object.keys(index).length} verified card images`);
}
main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
