'use strict';
// Practice hands show card tiles like the playtest hand; ship verified print images so opening a question
// never sends seven metadata requests.
const fs = require('fs');
const path = require('path');
const { hands } = require('../miniprogram/community/shared/catalog');
const { card } = require('../miniprogram/community/shared/contracts');
async function main() {
  const names = [...new Set(hands.flatMap((hand) => hand.cards))].sort();
  if (names.length > 75) throw new Error('Scryfall collection accepts at most 75 identifiers');
  const response = await fetch('https://api.scryfall.com/cards/collection', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Accept: 'application/json',
      'User-Agent': 'cEDH-Tutor/1.0',
    },
    body: JSON.stringify({ identifiers: names.map((name) => ({ name })) }),
    signal: AbortSignal.timeout(30000),
  });
  if (!response.ok) throw new Error(`Scryfall HTTP ${response.status}`);
  const result = await response.json();
  if (!Array.isArray(result.data) || result.not_found?.length)
    throw new Error('Incomplete hand card response');
  const index = {};
  for (const name of names) {
    const raw = result.data.find(
      (value) =>
        value.name === name || value.card_faces?.some((face) => face.name === name),
    );
    if (!raw) throw new Error(`Missing exact card: ${name}`);
    const normalized = card(raw);
    if (!normalized.thumb || !normalized.image)
      throw new Error(`Missing card image: ${name}`);
    index[name] = {
      printId: normalized.printId,
      name: normalized.name,
      thumb: normalized.thumb,
      image: normalized.image,
      artist: normalized.artist,
    };
  }
  fs.writeFileSync(
    path.join(__dirname, '../miniprogram/community/shared/hand-cards.js'),
    '// Generated by scripts/build-hand-card-index.js\nmodule.exports = ' +
      JSON.stringify(index, null, 2) +
      ';\n',
  );
  console.log(`Indexed ${names.length} verified hand card images`);
}
main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
